def test_control_current_boot_sequence_once_and_interrupts_sleep(context):
    paths, events, state = protocol.paths(context), [], {"permission": "admitted"}
    clock = Clock()

    class Adapter:
        model_name = "fake-local-model"
        recognize = prepare = no_computation

        def __init__(self, _context):
            pass

    class Engine:
        def __init__(self, *_args, **_options):
            pass

        def step(self):
            events.append(("step", clock.value))
            return 10

        def retry(self):
            events.append(("retry", clock.value))

        def snapshot(self):
            return worker.empty_summary("idle")

        def close(self):
            events.append(("close", clock.value))

    controls = [("previous-boot", 1), (NONCE, 1), (NONCE, 1), (NONCE, 2), (NONCE, 1)]

    def on_sleep(value):
        index = len(value.sleeps) - 1
        if index < len(controls):
            nonce, sequence = controls[index]
            protocol.write_record(paths["control"], dict(binding(context, "asr_control", nonce),
                                                        action="retry", sequence=sequence))
        else:
            state["permission"] = "stop"

    clock.on_sleep = on_sleep
    assert run_fake(context, clock, permission_fn=lambda *_: state["permission"],
                    engine_factory=Engine, adapter_factory=Adapter) == 0
    retries = [value for name, value in events if name == "retry"]
    assert retries == pytest.approx([.4, .8])
    assert [value for name, value in events if name == "step"] == pytest.approx([0, .4, .8])
    assert len(clock.sleeps) == 6 and events[-1][0] == "close"


