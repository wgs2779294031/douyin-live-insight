@pytest.mark.skipif(os.name != "nt", reason="requires the actual Windows private Job")
def test_real_lane_admission_before_fake_adapter_and_stop_closes_owned_job(context, tmp_path):
    from scripts.local_asr import AsrLane
    from scripts.local_process import OwnedProcess, same_identity

    data = Path(context["data"])
    toy, adapter_marker, close_marker = tmp_path / "worker_toy.py", data / "adapter.marker", data / "closed.marker"
    toy.write_text(textwrap.dedent('''
        import json, os, pathlib, sys
        sys.path[:0] = [sys.argv[1], str(pathlib.Path(sys.argv[1]) / "scripts")]
        from scripts import asr_worker as worker, asr_protocol as protocol
        from scripts.backfill_tasks import process_identity
        from scripts.local_context import load_customer_context
        context = load_customer_context()
        class FakeAdapter:
            model_name = "fake-local-model"
            def __init__(self, context):
                state = protocol.permission(context, os.environ["DY_CUSTOMER_ROLE_NONCE"],
                    protocol.parent_from_environment(), process_identity(os.getpid()),
                    protocol.scope_from_environment())
                assert state == "admitted", state
                pathlib.Path(sys.argv[2]).write_text("admitted", encoding="utf-8")
            def prepare(self): raise AssertionError("no model")
            def recognize(self, source): raise AssertionError("no audio")
        class FakeEngine:
            def __init__(self, data, **options): self.publish = options["publish"]
            def step(self):
                self.publish(worker.empty_summary("idle"))
                return .05
            def retry(self): raise AssertionError("no retry requested")
            def snapshot(self): return worker.empty_summary("idle")
            def close(self): pathlib.Path(sys.argv[3]).write_text("closed", encoding="utf-8")
        raise SystemExit(worker.run(context, engine_factory=FakeEngine, adapter_factory=FakeAdapter))
    '''), encoding="utf-8")
    owned_values, requested_commands, observations = [], [], {}

    def spawn(command, *, env, cwd, log_path):
        # Production fixed command is checked; this Python-only test seam changes
        # the executable script, never an API/CLI bypass flag.
        requested_commands.append(command)
        assert command == [context["python"], "-B", str(ROOT / "scripts/asr_worker.py")]
        owned = OwnedProcess.start([context["python"], "-B", str(toy), str(ROOT),
                                   str(adapter_marker), str(close_marker)], env=env, cwd=cwd, log_path=log_path)
        owned_values.append(owned)
        return owned

    manager = SimpleNamespace(context=context, directory=data / ".local_app", stopping=False,
                              now=time.monotonic, spawn=spawn, child_env=lambda: dict(os.environ))
    lane = AsrLane(manager)

    def wait(predicate, seconds=10, tick=False):
        deadline = time.monotonic() + seconds
        while time.monotonic() < deadline:
            if tick:
                lane.tick()
            if predicate():
                return
            time.sleep(.02)
        log = data / ".local_app/logs/asr.log"
        pytest.fail("toy deadline expired; " + (log.read_text(encoding="utf-8") if log.exists() else "no log"))

    try:
        lane.tick()
        assert len(owned_values) == 1
        owned = owned_values[0]
        wait(lambda: lane.paths["ready"].exists())  # Deliberately no parent tick yet.
        assert not lane.paths["admission"].exists() and not adapter_marker.exists()
        observations["ready_before_admission"] = True
        ready = protocol.read_record(lane.paths["ready"])
        assert ready["nonce"] == lane.nonce and owned.worker_identity(ready) is not None
        lane.tick()
        assert lane.admitted
        wait(adapter_marker.exists, tick=True)
        assert adapter_marker.read_text(encoding="utf-8") == "admitted"
        assert protocol.matches(protocol.read_record(lane.paths["admission"]), context, lane.nonce,
                                lane.parent, lane.worker, "asr_admission", lane.scope)
        accepted = (lane.nonce, dict(lane.parent), dict(lane.worker), dict(lane.scope))
        lane.begin_stop()
        wait(lane.drained, tick=True)
        assert close_marker.read_text(encoding="utf-8") == "closed"
        assert owned.proc.poll() == 0 and owned.closed and owned.active_count() == 0
        assert lane.owned is None and not lane.snapshot()["resource_held"]
        release = protocol.read_record(lane.paths["directory"] / "release.json")
        assert release["empty"] is True
        assert protocol.matches(release, context, *accepted[:3], "asr_release", accepted[3])
        assert same_identity(release["root"], owned.identity)
        assert set(release["records"]) == {"ready", "status", "admission"}
        assert all(isinstance(value, str) and len(value) == 64 and set(value) <= set("0123456789abcdef")
                   for value in release["records"].values())
        assert len(requested_commands) == 1
        observations.update(adapter_only_after_admission=True, close_marker=True, normal_exit=0,
                            active_processes=0, job_closed=True, spawn_count=1, bound_empty_release=True)
    finally:
        observations["forced_cleanup"] = False
        for owned in owned_values:
            if not owned.closed:
                observations["forced_cleanup"] = True
                assert owned.close(force=True), "cleanup may touch only the exact Job spawned by this test"
        observations["all_owned_jobs_closed"] = all(value.closed and value.active_count() == 0 for value in owned_values)
        (tmp_path / "toy-cleanup.json").write_text(json.dumps(observations, indent=2), encoding="utf-8")
