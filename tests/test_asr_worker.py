@pytest.mark.parametrize("fault, expected", [
    ("valid", "admitted"), ("old_nonce", "waiting"), ("worker_pid_reuse", "unknown"),
    ("parent_unknown", "unknown"), ("parent_malformed_alive", "unknown"),
    ("parent_pid_reuse", "stop"), ("ancestry_missing", "unknown"),
    ("ancestry_newer_than_child", "unknown"), ("bad_app_stop", "unknown"),
    ("bad_specific_stop", "unknown"), ("old_specific_stop", "admitted"),
    ("current_specific_stop", "stop"), ("current_app_stop", "stop"), ("scope_mismatch", "unknown")])
def test_real_protocol_files_fail_closed_on_bad_ownership(context, identities, fault, expected):
    registry, ancestry = identities
    paths = protocol.paths(context)
    scope = protocol.ensure(context)
    admission = binding(context, "asr_admission", "previous-boot" if fault == "old_nonce" else NONCE)
    if fault == "scope_mismatch":
        admission["scope"]["ino"] += 1
    protocol.write_record(paths["admission"], admission)
    if fault == "worker_pid_reuse":
        registry[WORKER["pid"]] = dict(WORKER, created=WORKER["created"] + 1)
    elif fault == "parent_unknown":
        registry[PARENT["pid"]] = {"state": "unknown"}
    elif fault == "parent_malformed_alive":
        registry[PARENT["pid"]] = {"state": "alive", "pid": PARENT["pid"]}
    elif fault == "parent_pid_reuse":
        registry[PARENT["pid"]] = dict(PARENT, created=PARENT["created"] + 1)
    elif fault == "ancestry_missing":
        ancestry.clear()
    elif fault == "ancestry_newer_than_child":
        ancestry[WORKER["pid"]] = 333
        registry[333] = {"state": "alive", "pid": 333, "created": WORKER["created"] + 1}
    elif fault == "bad_app_stop":
        (Path(context["data"]) / ".local_app/application-stop.json").write_text('{"schema":1,"action":"stop"}', encoding="utf-8")
    elif fault == "bad_specific_stop":
        paths["stop"].write_text('{"schema":1,"action":"stop"}', encoding="utf-8")
    elif fault in ("old_specific_stop", "current_specific_stop"):
        stop = binding(context, "asr_stop", "previous-boot" if fault == "old_specific_stop" else NONCE)
        protocol.write_record(paths["stop"], dict(stop, action="stop"))
