class Clock:
    def __init__(self, on_sleep=None):
        self.value, self.sleeps, self.on_sleep = 0.0, [], on_sleep

    def monotonic(self):
        return self.value

    def wall(self):
        return 1800000000.0 + self.value

    def sleep(self, seconds):
        assert 0 < seconds <= .200001
        self.sleeps.append(seconds)
        assert len(self.sleeps) < 100, "fake loop must remain bounded"
        self.value += seconds
        if self.on_sleep:
            self.on_sleep(self)


