def test_worker_real_sweep_commits_and_projects_synthetic_source_then_stops(context, identities):
    from scripts import transcript_results as results

    data = Path(context["data"])
    folder = data / "audio_generated_2000-01-01"
    folder.mkdir()
    number, source = audio.reserve_segment(data, folder)
    synthetic = b"generated audio bytes only; no decoder" * 160
    with source.open("xb") as stream:
        stream.write(synthetic)
        stream.flush()
        os.fsync(stream.fileno())
    audio.publish_closed(data, folder, source, number, 100 + number, 160 + number)
    closure = (folder / ".segments" / (source.stem + ".json")).read_bytes()
    paths = protocol.paths(context)
    protocol.ensure(context)
    protocol.write_record(paths["admission"], binding(context, "asr_admission"))
    events, permission_calls = [], [0]

    class Adapter:
        model_name = "generated-fake-model"

        def __init__(self, _context):
            assert protocol.permission(context, NONCE, PARENT, WORKER) == "admitted"
            events.append("adapter")

        def signature(self):
            return ["generated-stable-model-dependency"]

        def prepare(self):
            events.append("prepare")

        def recognize(self, path):
            assert events == ["adapter", "prepare"]
            assert path == source and path.read_bytes() == synthetic
            events.append("recognize")
            return ([{"start": 0.0, "end": 1.0, "text": "generated integration utterance"}], 60.0)

    def permission(*args):
        permission_calls[0] += 1
        assert permission_calls[0] < 200, "integration must reach a bounded completion or fail"
        facts = results.validate_success(data, folder, source.name)
        if facts.get("current_result") and facts.get("projection_ready"):
            if not paths["stop"].exists():
                protocol.write_record(paths["stop"], dict(binding(context, "asr_stop"), action="stop"))
        return protocol.permission(*args)

    # engine_factory is deliberately omitted: worker imports and constructs its
    # actual SweepEngine, which invokes real 7A canonical/projection operations.
    assert run_fake(context, Clock(), permission_fn=permission, adapter_factory=Adapter) == 0
    assert events == ["adapter", "prepare", "recognize"]
    facts = results.validate_success(data, folder, source.name)
    assert facts["current_result"] and facts["projection_ready"] and facts["cleanup_eligible"]
    canonical = json.loads(results.result_path(data, folder, source.name).read_text(encoding="utf-8"))
    speech, receipt, _pending = results.projection_paths(data, folder)
    projected = [json.loads(line) for line in speech.read_text(encoding="utf-8").splitlines()]
    assert projected == canonical["rows"] and projected[0]["text"] == "generated integration utterance"
    assert receipt.is_file() and results.attempt_path(data, folder, source.name).is_file()
    assert source.read_bytes() == synthetic
    assert (folder / ".segments" / (source.stem + ".json")).read_bytes() == closure
    summary = protocol.read_record(paths["status"])["summary"]
    assert summary["state"] == "stopping" and summary["last_completed_at"] is not None
    assert summary["counts"]["complete"] == 1 and paths["stop"].is_file()


